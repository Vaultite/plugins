// Writes the object parser's data tables from what Emacs reports at runtime (oracle/tables.el):
//   node org/.test/gen-tables.ts
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"

const HERE = path.dirname(new URL(import.meta.url).pathname), OUT = path.join(HERE, "../parser/objects")
const j = JSON.parse(execFileSync("emacs", ["-Q", "--batch", "-l", path.join(HERE, "oracle/tables.el")], { encoding: "utf8", maxBuffer: 1 << 26 }))
const head = "// Generated by org/.test/gen-tables.ts from Emacs's runtime data: don't edit.\n"

const entities = j.entities.map((e: unknown[]) => JSON.stringify(e)).join(",\n  ")
fs.writeFileSync(path.join(OUT, "entities-data.ts"), `${head}// [name, latex, latexMathP, html, ascii, latin1, utf8], in Emacs's order.
export const ENTITIES: [string, string, boolean, string, string, string, string][] = [\n  ${entities},\n]\n`)

// Syntax classes as flat [start, end] pairs per class; line-breakable characters likewise.
const byClass = new Map<string, number[]>()
for (const [a, b, k] of j.syntax as [number, number, string][]) {
  if (!byClass.has(k)) byClass.set(k, [])
  byClass.get(k)!.push(a, b)
}
const classes = [...byClass].map(([k, v]) => `  ${JSON.stringify(k)}: [${v.join(",")}],`).join("\n")
const breakable = (j.breakable as [number, number][]).flatMap(([a, b]) => [a, b]).join(",")
// Scripts as [start, end, index into SCRIPT_NAMES] triples; categories as [start, end] pairs per category.
const names: string[] = [], scripts: number[] = []
for (const [a, b, k] of j.scripts as [number, number, string][]) {
  if (!names.includes(k)) names.push(k)
  scripts.push(a, b, names.indexOf(k))
}
const cats = new Map<string, number[]>()
for (const [a, b, ks] of j.categories as [number, number, string][]) for (const k of ks) {
  if (!cats.has(k)) cats.set(k, [])
  cats.get(k)!.push(a, b)
}
const catLines = [...cats].map(([k, v]) => `  ${JSON.stringify(k)}: [${v.join(",")}],`).join("\n")
fs.writeFileSync(path.join(OUT, "chars-data.ts"), `${head}// An Org buffer's syntax class of every character, as sorted inclusive [start, end] pairs per class.
export const SYNTAX: Record<string, number[]> = {\n${classes}\n}

// Characters a line may break at (category "|"): CJK and the like.
export const BREAKABLE = [${breakable}]

// Where words break between two word characters: at a change of script, unless a combining pair of categories
// joins them; within a script, only between a separating pair (both as [before, after]; "" is any).
export const SCRIPT_NAMES = ${JSON.stringify(names)}
export const SCRIPTS = [${scripts.join(",")}]
export const CATEGORIES: Record<string, number[]> = {\n${catLines}\n}
export const COMBINING: [string, string][] = ${JSON.stringify(j.combining)}
export const SEPARATING: [string, string][] = ${JSON.stringify(j.separating)}\n`)
console.log(`${j.entities.length} entities, ${j.syntax.length} syntax runs`)
